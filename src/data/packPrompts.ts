export function getPackPrompt(kind: PackResourceKind, mode: 'new' | 'update'): string {
  const publication = mode === 'update' ? '本次为更新已有资源。' : '本次为首次发布。';
  return `${publication}\n\n${PACK_PROMPTS[kind]}`;
}
